"""Draw the brows logo for each expression as 48x48 OLED bitmaps and paste them into main.py.

Runs on your computer, not the board. The shapes match web/brows.js; keep the two in sync.

    py openmv/make_brows_icons.py            # rewrites the BROWS block in openmv/main.py
    py openmv/make_brows_icons.py --preview  # also saves brows_preview.png next to this script
"""

import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
SIZE = 48
VIEW = (10, 8, 90, 88)       # part of the 100x100 design box that fills the icon
SCALE = 8                    # draw large, then shrink, for clean edges
BROW_WIDTH = 8

SHAPES = {
    "happy":    ("M18 40 Q31 28 44 36", "M56 36 Q69 28 82 40", (7, -13, -5, 2), (7, -13, -5, 2)),
    "angry":    ("M16 32 Q30 37 44 44", "M56 44 Q70 37 84 32", (6, -5, 11, 1), (6, -5, 11, 1)),
    "surprise": ("M18 30 Q31 13 44 27", "M56 27 Q69 13 82 30", (7, -16, 16, 0), (7, -16, 16, 0)),
    "neutral":  ("M18 38 Q31 38 44 38", "M56 38 Q69 38 82 38", (6, -12, 12, 0), (6, -12, 12, 0)),
    "sad":      ("M18 40 Q31 38 44 31", "M56 31 Q69 38 82 40", (6, -7, 10, 2), (6, -7, 10, 2)),
    "unsure":   ("M18 39 Q31 37 44 39", "M56 31 Q69 19 82 29", (6, -10, 10, 1), (6, -13, 13, 0)),
}


def quad(p0, c, p1, steps=24):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t * t * p1[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t * t * p1[1])
            for t in (i / steps for i in range(steps + 1))]


def brow_points(path):
    x0, y0, cx, cy, x1, y1 = map(float, re.findall(r"-?\d+(?:\.\d+)?", path))
    return quad((x0, y0), (cx, cy), (x1, y1))


def eye_points(cx, hw, top, bottom, dy):
    y = 58 + dy
    return quad((cx - hw, y), (cx, y + top), (cx + hw, y))[:-1] + quad((cx + hw, y), (cx, y + bottom), (cx - hw, y))


def render(mood):
    left, right, eye_l, eye_r = SHAPES[mood]
    span = VIEW[2] - VIEW[0]
    px = SIZE * SCALE / span
    to_px = lambda pts: [((x - VIEW[0]) * px, (y - VIEW[1]) * px) for x, y in pts]
    img = Image.new("L", (SIZE * SCALE, SIZE * SCALE), 0)
    draw = ImageDraw.Draw(img)
    radius = BROW_WIDTH * px / 2
    for path in (left, right):
        x0, y0, cx, cy, x1, y1 = map(float, re.findall(r"-?\d+(?:\.\d+)?", path))
        for x, y in to_px(quad((x0, y0), (cx, cy), (x1, y1), steps=120)):   # round brush along the curve
            draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill=255)
    for cx, params in ((31, eye_l), (69, eye_r)):
        pts = to_px(eye_points(cx, *params))
        draw.polygon(pts, fill=255)
        draw.line(pts + [pts[0]], fill=255, width=round(2 * px), joint="curve")
    return img.resize((SIZE, SIZE), Image.Resampling.LANCZOS).point(lambda v: 255 if v >= 110 else 0)


def to_hlsb(img):
    out = bytearray()
    for y in range(SIZE):
        for xb in range(0, SIZE, 8):
            byte = 0
            for bit in range(8):
                if img.getpixel((xb + bit, y)):
                    byte |= 0x80 >> bit
            out.append(byte)
    return bytes(out)


def main():
    icons = {mood: render(mood) for mood in SHAPES}
    lines = ["# BROWS-START (generated by make_brows_icons.py; 48x48 MONO_HLSB bitmaps)", "BROWS = {"]
    for mood, img in icons.items():
        lines.append("    %r: %r," % (mood, to_hlsb(img)))
    lines += ["}", 'BROWS_ALIAS = {"fear": "surprise", "disgust": "angry"}', "# BROWS-END"]
    main_py = HERE / "main.py"
    text = main_py.read_text(encoding="utf-8")
    block = "\n".join(lines)
    new = re.sub(r"# BROWS-START.*?# BROWS-END", lambda _: block, text, flags=re.S)
    if new == text and "# BROWS-START" not in text:
        sys.exit("main.py has no BROWS-START / BROWS-END block")
    main_py.write_text(new, encoding="utf-8")
    print("updated", main_py)
    if "--preview" in sys.argv:
        sheet = Image.new("L", (len(icons) * (SIZE + 8) + 8, SIZE + 16), 40)
        for i, img in enumerate(icons.values()):
            sheet.paste(img, (8 + i * (SIZE + 8), 8))
        sheet = sheet.resize((sheet.width * 4, sheet.height * 4), Image.Resampling.NEAREST)
        sheet.save(HERE / "brows_preview.png")
        print("saved", HERE / "brows_preview.png")


if __name__ == "__main__":
    main()
