# Minimal SSD1306 I2C driver adapted from MicroPython Lib, MIT license (see SSD1306-LICENSE.txt).
class SSD1306_I2C(framebuf.FrameBuffer):
    def __init__(self, width, height, i2c, addr=0x3C):
        self.width = width
        self.height = height
        self.pages = height // 8
        self.i2c = i2c
        self.addr = addr
        self.cmd_buf = bytearray(2)
        self.buffer = bytearray(self.pages * width)
        super().__init__(self.buffer, width, height, framebuf.MONO_VLSB)
        for cmd in (
            0xAE,  # display off
            0x20, 0x00,  # horizontal addressing mode
            0x40,  # start line 0
            0xA1,  # column 127 mapped to SEG0
            0xA8, height - 1,  # multiplex ratio
            0xC8,  # scan COM[N] to COM0
            0xD3, 0x00,  # display offset 0
            0xDA, 0x12 if height == 64 else 0x02,  # COM pin config
            0xD5, 0x80,  # clock divide
            0xD9, 0xF1,  # pre-charge (internal VCC)
            0xDB, 0x30,  # VCOMH deselect
            0x81, 0xFF,  # contrast
            0xA4,  # output follows RAM
            0xA6,  # not inverted
            0x8D, 0x14,  # enable charge pump
            0xAF,  # display on
        ):
            self.write_cmd(cmd)
        self.fill(0)
        self.show()

    def write_cmd(self, cmd):
        self.cmd_buf[0] = 0x80
        self.cmd_buf[1] = cmd
        self.i2c.writeto(self.addr, self.cmd_buf)

    def show(self):
        for cmd in (0x21, 0, self.width - 1, 0x22, 0, self.pages - 1):
            self.write_cmd(cmd)
        self.i2c.writevto(self.addr, (b"\x40", self.buffer))


def start_display():
    try:
        bus = I2C(1, freq=400000)
        found = bus.scan()
        for address in OLED_ADDRESSES:
            if address in found:
                return SSD1306_I2C(OLED_WIDTH, OLED_HEIGHT, bus, addr=address)
        print("No OLED at 0x3C/0x3D. Continuing without display.")
    except OSError as error:
        print("OLED unavailable:", error)
    return None


def draw_big_text(oled, text, y, max_scale=3):
    # The built-in font is 8x8, so render it into a scratch buffer and blow each pixel up.
    width = len(text) * 8
    scale = max(1, min(max_scale, OLED_WIDTH // width))
    buf = bytearray(width)
    glyphs = framebuf.FrameBuffer(buf, width, 8, framebuf.MONO_VLSB)
    glyphs.text(text, 0, 0, 1)
    x0 = (OLED_WIDTH - width * scale) // 2
    for sx in range(width):
        column = buf[sx]
        if not column:
            continue
        for sy in range(8):
            if column & (1 << sy):
                oled.fill_rect(x0 + sx * scale, y + sy * scale, scale, scale, 1)


def draw_centered_text(oled, text, y):
    oled.text(text, (OLED_WIDTH - len(text) * 8) // 2, y)


def show_message(oled, line1, line2=""):
    oled.fill(0)
    draw_centered_text(oled, line1, 24)
    if line2:
        draw_centered_text(oled, line2, 36)
    oled.show()


def draw_bar(oled, x, y, width, pct):
    oled.rect(x, y, width, 10, 1)
    oled.fill_rect(x + 2, y + 2, (width - 4) * pct // 100, 6, 1)


def brows_icon(label):
    data = BROWS.get(label) or BROWS.get(BROWS_ALIAS.get(label, ""))
    if data is None:
        return None
    return framebuf.FrameBuffer(bytearray(data), 48, 48, framebuf.MONO_HLSB)


def show_expression(oled, icons, label, score):
    pct = round(100 * score)
    confident = score >= MIN_SCORE
    icon = icons.get(label if confident else "unsure")
    oled.fill(0)
    if icon is not None:
        oled.blit(icon, 2, 8)
        oled.text(label.upper() if confident else "UNSURE", 56, 14)
        oled.text("%d%%" % pct if confident else label + "?", 56, 28)
        draw_bar(oled, 56, 42, OLED_WIDTH - 60, pct)
    elif confident:
        draw_big_text(oled, label, 4)
        draw_centered_text(oled, "%d%%" % pct, 36)
        draw_bar(oled, 4, 50, OLED_WIDTH - 8, pct)
    else:
        draw_big_text(oled, "?", 4)
        draw_centered_text(oled, "%s %d%%" % (label, pct), 36)
        draw_bar(oled, 4, 50, OLED_WIDTH - 8, pct)
    oled.show()


def exists(path):
    try:
        os.stat(path)
        return True
    except OSError:
        return False


def load_model():
    rom_model = ROMFS_DIR + "/" + MODEL_FILE
    if exists(rom_model):
        model = ml.Model(rom_model)
        labels_path = ROMFS_DIR + "/" + LABELS_FILE
    else:
        model = ml.Model(FLASH_DIR + "/" + MODEL_FILE)
        labels_path = FLASH_DIR + "/" + LABELS_FILE
    with open(labels_path) as label_file:
        labels = [line.strip() for line in label_file if line.strip()]
    if tuple(model.input_shape) != ((1, 48, 48, 1),) or tuple(model.output_shape) != ((1, len(labels)),):
        raise ValueError("Use the supplied expression.tflite and labels.txt together")
    return model, labels


class BrowserLink:
    def __init__(self):
        self.poller = select.poll()
        self.poller.register(sys.stdin, select.POLLIN)
        self.pending = ""
        self.last_request = None

    def active(self):
        while self.poller.poll(0):
            char = sys.stdin.read(1)
            if not char:
                break
            if char == "\n":
                if self.pending.strip() == "stream":
                    self.last_request = time.ticks_ms()
                self.pending = ""
            elif len(self.pending) < 16:
                self.pending += char
        if self.last_request is None:
            return False
        return time.ticks_diff(time.ticks_ms(), self.last_request) < STREAM_TIMEOUT_MS

    def send(self, frame, reading):
        jpeg = frame.to_jpeg(quality=STREAM_JPEG_QUALITY, copy=True)
        sys.stdout.write("@IO\t" + json.dumps(reading) + "\t" + binascii.b2a_base64(jpeg).decode())


def start_link():
    try:
        return BrowserLink()
    except (AttributeError, OSError, TypeError) as error:
        print("USB streaming unavailable:", error)
    return None


def start_camera():
    if csi is not None:
        camera = csi.CSI()
        camera.reset()
        camera.pixformat(csi.GRAYSCALE)
        camera.framesize(csi.QQVGA)
        camera.snapshot(time=1200)
        return camera

    sensor.reset()
    sensor.set_pixformat(sensor.GRAYSCALE)
    sensor.set_framesize(sensor.QQVGA)
    sensor.skip_frames(time=1200)
    return sensor


